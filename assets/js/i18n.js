function getActiveLanguage() {
  return localStorage.getItem("plastokast_lang") || "en";
}

function getActiveCurrency() {
  return localStorage.getItem("plastokast_currency") || "USD";
}

function formatPrice(usdMin, usdMax) {
  const current = getActiveCurrency();
  const conv = CURRENCY_CONVERSIONS[current] || CURRENCY_CONVERSIONS.USD;
  const min = (usdMin * conv.rate).toFixed(2);
  const max = (usdMax * conv.rate).toFixed(2);
  return `${conv.symbol}${min} - ${conv.symbol}${max}`;
}

function getProductPriceText(productId) {
  const range = DEFAULT_PRICES[productId] || { min: 10.00, max: 50.00 };
  return formatPrice(range.min, range.max);
}

function applyLocalization() {
  const lang = getActiveLanguage();
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  
  // Set dir to rtl for Arabic
  document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
  document.documentElement.lang = lang;
  
  // Translate static text elements with data-i18n attribute
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = dict[key];
      } else {
        el.textContent = dict[key];
      }
    }
  });

  // Dynamically update navbar menus
  document.querySelectorAll(".nav-links a, .footer-links a").forEach(link => {
    const text = link.textContent.trim().toLowerCase().replace(" us", "");
    if (text === "home" || text === "products" || text === "about" || text === "contact" || text === "downloads") {
      link.textContent = dict[text];
      link.setAttribute("data-i18n", text);
    }
  });

  // Dispatch global localization event for components to listen to
  window.dispatchEvent(new CustomEvent("i18nChanged", { detail: { lang, dict } }));
}

function applyCurrency() {
  const currency = getActiveCurrency();
  // Find all elements displaying prices and update them
  document.querySelectorAll("[data-price-min]").forEach(el => {
    const min = parseFloat(el.getAttribute("data-price-min"));
    const max = parseFloat(el.getAttribute("data-price-max"));
    if (!isNaN(min) && !isNaN(max)) {
      el.textContent = formatPrice(min, max);
    }
  });
  window.dispatchEvent(new CustomEvent("currencyChanged", { detail: { currency } }));
}

document.addEventListener("DOMContentLoaded", () => {
  // Apply initial i18n and currency state
  applyLocalization();
  applyCurrency();
});
